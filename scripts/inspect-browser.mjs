import { chromium } from "@playwright/test";
import { mkdir, writeFile, readFile } from "node:fs/promises";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: "es-PE" });
const consoleMessages = [], failures = [];
page.on("console", m => { if (["error", "warning"].includes(m.type())) consoleMessages.push({ type: m.type(), text: m.text() }); });
page.on("requestfailed", r => failures.push({ url: r.url(), failure: r.failure()?.errorText }));
await page.goto("http://127.0.0.1:3000");
await page.getByRole("heading", { level: 1 }).waitFor();
await page.keyboard.press("Tab");
const firstFocus = await page.evaluate(() => document.activeElement?.textContent);
const map = page.locator(".maplibregl-canvas");
await map.waitFor();
await map.click({ position: { x: 80, y: 120 } });
const changedLat = await page.getByLabel("Latitud", { exact: true }).inputValue();
if (changedLat === "-8.42") throw new Error("El clic del mapa no cambió las coordenadas");
await page.getByRole("button", { name: "Cargar caso ilustrativo" }).click();
await page.getByRole("button", { name: "Consultar clima y comparar" }).click();
await page.getByText("Informe disponible", { exact: true }).waitFor({ state: "attached", timeout: 60_000 });
await page.getByRole("heading", { name: "Clima histórico · NASA POWER" }).waitFor();
await page.locator("#rotaciones").scrollIntoViewIfNeeded();
await page.screenshot({ path: "docs/evidence/comparison-desktop.png" });
await page.getByRole("heading", { level: 1 }).scrollIntoViewIfNeeded();
await page.screenshot({ path: "docs/evidence/viewport-desktop.png" });
const downloadEvent = page.waitForEvent("download");
await page.getByRole("button", { name: "Descargar JSON" }).click();
const download = await downloadEvent;
const downloadedReport = JSON.parse(await readFile(await download.path(), "utf8"));
if (downloadedReport.climate?.days.length !== 540 || downloadedReport.strategies?.length !== 3) throw new Error("Informe descargado incompleto");
await page.pdf({ path: "docs/evidence/report-print.pdf", format: "A4", printBackground: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.getByRole("heading", { level: 1 }).scrollIntoViewIfNeeded();
await page.screenshot({ path: "docs/evidence/viewport-mobile.png" });
const metrics = await page.evaluate(() => ({ viewport: innerWidth, documentWidth: document.documentElement.scrollWidth, title: document.title }));
await mkdir("docs/evidence", { recursive: true });
await writeFile("docs/evidence/browser-inspection.json", JSON.stringify({ date: new Date().toISOString(), browser: "Playwright Chromium", firstFocus, changedLat, metrics, downloadedDays: downloadedReport.climate.days.length, consoleMessages, failures }, null, 2));
console.log(JSON.stringify({ firstFocus, changedLat, metrics, consoleMessages, failures }, null, 2));
await browser.close();
